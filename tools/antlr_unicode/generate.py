#!/usr/bin/env python3
"""Regenerate pinned ANTLR Unicode/case data; never used by ordinary builds."""
import argparse
import hashlib
import pathlib
import subprocess
import tempfile

PIN = 'eae2dfa119a64327444672aff63e9ec35a20180dc5b8090b7a6ab85125df4d76'
ROOT = pathlib.Path(__file__).resolve().parents[2]

def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('jar', type=pathlib.Path)
    parser.add_argument('--output', type=pathlib.Path, default=ROOT / 'libs/extras/grammars/antlr_to_pg/unicode_data.w')
    args = parser.parse_args()
    jar = args.jar.resolve()
    if hashlib.sha256(jar.read_bytes()).hexdigest() != PIN:
        raise SystemExit('ANTLR jar SHA-256 mismatch')
    version = subprocess.run(['java', '-version'], capture_output=True, text=True, check=True).stderr
    if 'version "17.' not in version:
        raise SystemExit('case mapping reference requires Java 17')
    with tempfile.TemporaryDirectory() as work:
        subprocess.run(['javac', '-cp', str(jar), '-d', work, str(pathlib.Path(__file__).with_name('UnicodeDump.java'))], check=True)
        data = subprocess.check_output(['java', '-cp', work + ':' + str(jar), 'UnicodeDump'], text=True)
    digest = hashlib.sha256(data.encode()).hexdigest()
    if digest != '866e7aa3a82fa98b5ce14e0b635fb3b25e1d8a51b3e4589026fe5929dcba550d':
        raise SystemExit('reference Unicode/case data checksum mismatch')
    props, aliases, cases = [], [], []
    for line in data.splitlines():
        fields = line.split('\t')
        if fields[0] == 'P': props.append((fields[1], ','.join(fields[2:])))
        elif fields[0] == 'A': aliases.append((fields[1], fields[2]))
        elif fields[0] == 'C': cases.append(tuple(map(int, fields[1:])))
    lines = ['# Generated by tools/antlr_unicode/generate.py; do not edit.',
             '# Reference: ANTLR 4.13.2 UnicodeData and Java 17 Character mappings.',
             '# See tools/antlr_unicode/README.md for provenance and licenses.',
             'import lib.lib', '', 'map[char*, char*] g_at_unicode_properties',
             'map[int, int] g_at_unicode_lower', 'map[int, int] g_at_unicode_upper', '']
    assignments = [f'\tg_at_unicode_properties[c"{k}"] = c"{v}"' for k, v in props]
    assignments += [f'\tg_at_unicode_properties[c"{k}"] = g_at_unicode_properties[c"{v}"]' for k, v in aliases]
    assignments += [f'\tg_at_unicode_lower[{c}] = {lo}\n\tg_at_unicode_upper[{c}] = {hi}' for c, lo, hi in cases]
    chunks = [assignments[i:i+100] for i in range(0, len(assignments), 100)]
    for i, chunk in enumerate(chunks):
        lines += [f'void at_unicode_data_part_{i}():'] + chunk + ['', '']
    lines += ['void at_unicode_data_init():', '\tif (g_at_unicode_properties != 0): return',
              '\tg_at_unicode_properties = new map[char*, char*]', '\tg_at_unicode_lower = new map[int, int]',
              '\tg_at_unicode_upper = new map[int, int]']
    lines += [f'\tat_unicode_data_part_{i}()' for i in range(len(chunks))]
    args.output.write_text('\n'.join(lines) + '\n')
    print(f'{len(props)} properties, {len(aliases)} aliases, {len(cases)} case mappings; source SHA256 {hashlib.sha256(data.encode()).hexdigest()}')

if __name__ == '__main__': main()
