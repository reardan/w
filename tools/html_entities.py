#!/usr/bin/env python3
"""Regenerate HTML named references from the pinned WHATWG entities.json (offline)."""
import argparse
import hashlib
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "libs/extras/html/entities.json"
OUTPUT = ROOT / "libs/extras/html/entities.w"
SHA256 = "d741d877ac77c4194c4ad526b5b4a19aef8dfe411ab840a466891cdbb9f362e6"


def literal(data):
    return ''.join(chr(b) if 32 <= b < 127 and b not in (34, 92)
                   else f"\\x{b:02x}" for b in data)


def generate():
    raw = DATA.read_bytes()
    if hashlib.sha256(raw).hexdigest() != SHA256:
        raise SystemExit("HTML entities.json checksum mismatch; review provenance before updating the pin")
    entries = json.loads(raw)
    records = bytearray()
    offsets = bytearray()
    for name, entry in sorted(entries.items()):
        if not re.fullmatch(r"&[A-Za-z0-9]+;?", name):
            raise SystemExit(f"Invalid entity name: {name!r}")
        text = entry["characters"]
        if not 1 <= len(text) <= 2 or [ord(c) for c in text] != entry["codepoints"]:
            raise SystemExit(f"Invalid entity value: {name}")
        if any(ord(c) == 0 or 0xD800 <= ord(c) <= 0xDFFF for c in text):
            raise SystemExit(f"Non-scalar entity value: {name}")
        offsets.extend(len(records).to_bytes(2, "little"))
        records.extend(name[1:].encode("ascii") + b"\0" + text.encode("utf-8") + b"\0")
    if len(records) > 65535:
        raise SystemExit("HTML entity data exceeds its 16-bit offset format")
    return "\n".join([
        "# Generated by tools/html_entities.py; do not edit.",
        "# Copyright WHATWG (Apple, Google, Mozilla, Microsoft).",
        "# BSD-3-Clause for source-code incorporation; see WHATWG-LICENSE.txt.",
        f"# entities.json SHA-256: {SHA256}",
        "import lib.lib", "",
        f"const int HTML_ENTITY_COUNT = {len(entries)}",
        f"const int HTML_ENTITY_MAX_NAME = {max(len(n) - 1 for n in entries)}", "",
        "# Borrowed immutable name-NUL / UTF-8-value-NUL records, sorted by name.",
        "# Bytewise little-endian offsets work on every target without alignment assumptions.",
        "char* html_entity_entry(int index):",
        "\tif ((index < 0) || (index >= HTML_ENTITY_COUNT)): return 0",
        f'\tchar* offsets = c"{literal(offsets)}"',
        f'\tchar* records = c"{literal(records)}"',
        "\tint offset = (offsets[index * 2] & 255) | ((offsets[index * 2 + 1] & 255) << 8)",
        "\treturn records + offset", "",
    ])


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    result = generate()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != result:
            raise SystemExit("HTML entity tables need regeneration: python3 tools/html_entities.py")
    else:
        OUTPUT.write_text(result)
