#!/usr/bin/env python3
"""Generate pinned Unicode 12.1 default casing tables (no network at build time).

To refresh the compact source, download the three named files from
https://www.unicode.org/Public/12.1.0/ucd/ and pass --ucd-dir DIRECTORY.
The exact SHA-256 pins below are verified before deriving any records.
"""
import argparse
import hashlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / 'libs/extras/javascript/unicode_case_12_1.txt'
OUTPUT = ROOT / 'libs/extras/javascript/unicode_case.w'
PINS = {
    'UnicodeData.txt': '93ab1acd8fd9d450463b50ae77eab151a7cda48f98b25b56baed8070f80fc936',
    'SpecialCasing.txt': '817ce2e9edca8e075a153f54b8f3b020345e37652cd2bda9b1495c366af17e7e',
    'DerivedCoreProperties.txt': 'a6eb7a8671fb532fbd88c37fd7b20b5b2e7dbfc8b121f74c14abe2947db0da68',
}


def compact(directory):
    sources = {}
    for name, expected in PINS.items():
        raw = (directory / name).read_bytes()
        if hashlib.sha256(raw).hexdigest() != expected:
            raise ValueError(f'{name}: SHA-256 does not match Unicode 12.1 pin')
        sources[name] = raw.decode('utf-8')
    mappings = {}
    for line in sources['UnicodeData.txt'].splitlines():
        fields = line.split(';')
        code = int(fields[0], 16)
        lower = fields[13] or fields[0]
        upper = fields[12] or fields[0]
        if lower != fields[0] or upper != fields[0]:
            mappings[code] = (lower, upper)
    for line in sources['SpecialCasing.txt'].splitlines():
        fields = [f.strip() for f in line.split('#')[0].split(';')]
        if not fields[0] or fields[4]:
            continue  # Final_Sigma is implemented by the runtime; locale rules excluded.
        mappings[int(fields[0], 16)] = (fields[1], fields[3])
    lines = ['# Unicode 12.1.0 default casing subset; Copyright Unicode, Inc.',
             '# See UNICODE-LICENSE.txt. Derived from https://www.unicode.org/Public/12.1.0/ucd/',
             '# M; code point; full lowercase; full uppercase', '# P; property; inclusive range']
    lines += [f'# {name} SHA-256 {digest}' for name, digest in PINS.items()]
    lines += [f'M;{code:04X};{lower};{upper}' for code, (lower, upper) in sorted(mappings.items())]
    for line in sources['DerivedCoreProperties.txt'].splitlines():
        fields = [f.strip() for f in line.split('#')[0].split(';')]
        if len(fields) != 2 or fields[1] not in ('Cased', 'Case_Ignorable'):
            continue
        span = fields[0] if '..' in fields[0] else fields[0] + '..' + fields[0]
        lines.append(f'P;{fields[1]};{span}')
    return '\n'.join(lines) + '\n'


def escaped(raw):
    return ''.join(f'\\x{c:02x}' for c in raw)


def u24(value):
    return value.to_bytes(3, 'little')


def generate(source):
    maps = {'lower': [], 'upper': []}
    props = {'Cased': [], 'Case_Ignorable': []}
    for line in source.splitlines():
        if not line or line.startswith('#'):
            continue
        fields = line.split(';')
        if fields[0] == 'M':
            code = int(fields[1], 16)
            for column, name in ((2, 'lower'), (3, 'upper')):
                values = [int(v, 16) for v in fields[column].split()]
                if values != [code]:
                    maps[name].append((code, values))
        else:
            first, last = [int(v, 16) for v in fields[2].split('..')]
            spans = props[fields[1]]
            if spans and first == spans[-1][1] + 1:
                spans[-1] = (spans[-1][0], last)
            else:
                spans.append((first, last))
    lines = ['# Generated by tools/javascript_unicode_case.py; Unicode 12.1.0.',
             '# Copyright Unicode, Inc.; see UNICODE-LICENSE.txt and unicode_case_12_1.txt.',
             'import libs.extras.javascript.unicode', '',
             'int js_unicode_case_offset(char* index, int count, int codepoint):',
             '\tint lo = 0', '\tint hi = count', '\twhile (lo < hi):',
             '\t\tint mid = lo + (hi - lo) / 2',
             '\t\tint code = js_unicode_u24(index, mid * 6)',
             '\t\tif (codepoint < code): hi = mid',
             '\t\telse if (codepoint > code): lo = mid + 1',
             '\t\telse: return js_unicode_u24(index, mid * 6 + 3)', '\treturn -1', '']
    for name, mappings in maps.items():
        index, values = bytearray(), bytearray()
        for code, mapped in mappings:
            index += u24(code) + u24(len(values))
            values += bytes([len(mapped)]) + b''.join(u24(c) for c in mapped)
        lines += [f'char* js_unicode_{name}_mapping(int codepoint):',
                  f'\tchar* index = c"{escaped(index)}"',
                  f'\tchar* values = c"{escaped(values)}"',
                  f'\tint offset = js_unicode_case_offset(index, {len(mappings)}, codepoint)',
                  '\tif (offset < 0): return 0', '\treturn values + offset', '']
    for name, spans in props.items():
        raw = b''.join(u24(lo) + u24(hi) for lo, hi in spans)
        lines += [f'int js_unicode_{name.lower()}(int codepoint):',
                  f'\tchar* data = c"{escaped(raw)}"',
                  f'\treturn js_unicode_contains(data, {len(spans)}, codepoint)', '']
    return '\n'.join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--ucd-dir', type=Path)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    source = compact(args.ucd_dir) if args.ucd_dir else DATA.read_text()
    if args.ucd_dir:
        if args.check:
            assert DATA.read_text() == source, 'compact Unicode casing data is stale'
        else:
            DATA.write_text(source)
    generated = generate(source)
    if args.check:
        assert OUTPUT.read_text() == generated, 'Unicode casing table needs regeneration'
    else:
        OUTPUT.write_text(generated)


if __name__ == '__main__':
    main()
