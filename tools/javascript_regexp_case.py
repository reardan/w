#!/usr/bin/env python3
"""Generate libs/extras/javascript/regexp_case.w from the vendored UCD files.

RegExp Canonicalize (ECMA-262 sec-runtime-semantics-canonicalize-ch):
- with the u flag: simple case folding (CaseFolding.txt status C and S);
- without u: toUppercase when the full mapping is a single code unit and does
  not map a non-ASCII character into ASCII.

Tables are run-length encoded as (first, last, delta, stride) records so the
interpreter can also enumerate the preimages of a canonical character.
Usage: tools/javascript_regexp_case.py [--check]
"""
from __future__ import annotations

from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
UCD = ROOT / "tools/unicode"
OUTPUT = ROOT / "libs/extras/javascript/regexp_case.w"


def version() -> str:
    first = (UCD / "CaseFolding.txt").read_text().splitlines()[0]
    return first.split("-")[1].split(".txt")[0]


def fold_map() -> dict[int, int]:
    result = {}
    for line in (UCD / "CaseFolding.txt").read_text().splitlines():
        line = line.split("#")[0].strip()
        if not line:
            continue
        code, status, mapping = [part.strip() for part in line.split(";")[:3]]
        if status in {"C", "S"}:
            result[int(code, 16)] = int(mapping, 16)
    return result


def upper_map() -> dict[int, int]:
    multi = set()
    for line in (UCD / "SpecialCasing.txt").read_text().splitlines():
        line = line.split("#")[0].strip()
        if not line:
            continue
        fields = [part.strip() for part in line.split(";")]
        # Conditional mappings (a fifth field) do not apply to toUppercase.
        if len(fields) > 4 and fields[4]:
            continue
        if len(fields[3].split()) > 1:
            multi.add(int(fields[0], 16))
    result = {}
    for line in (UCD / "UnicodeData.txt").read_text().splitlines():
        fields = line.split(";")
        if not fields[12]:
            continue
        code = int(fields[0], 16)
        upper = int(fields[12], 16)
        if code in multi or code > 0xFFFF or upper > 0xFFFF:
            continue
        if code >= 128 and upper < 128:
            continue
        result[code] = upper
    return result


def runs(mapping: dict[int, int]) -> list[tuple[int, int, int, int]]:
    out: list[list[int]] = []
    for code in sorted(mapping):
        delta = mapping[code] - code
        if out:
            first, last, run_delta, stride = out[-1]
            if run_delta == delta:
                # A stride-2 run must not straddle another mapped code point,
                # so records never overlap and binary search stays valid.
                if stride == 0 and (code - last == 1 or (code - last == 2 and last + 1 not in mapping)):
                    out[-1][1] = code
                    out[-1][3] = code - last
                    continue
                if stride and code - last == stride and (stride == 1 or last + 1 not in mapping):
                    out[-1][1] = code
                    continue
        out.append([code, code, delta, 0])
    return [(a, b, c, d or 1) for a, b, c, d in out]


def encode(records: list[tuple[int, int, int, int]]) -> str:
    data = bytearray()
    for first, last, delta, stride in records:
        biased = delta + (1 << 23)
        for value in (first, last, biased):
            data += bytes([value & 255, (value >> 8) & 255, (value >> 16) & 255])
        data.append(stride)
    return "".join(f"\\x{byte:02x}" for byte in data)


def render() -> str:
    fold = runs(fold_map())
    upper = runs(upper_map())
    return f'''# Generated by tools/javascript_regexp_case.py from tools/unicode
# CaseFolding.txt, SpecialCasing.txt and UnicodeData.txt (Unicode {version()}).
# Copyright Unicode, Inc.; see UNICODE-LICENSE.txt.
# Records: first, last, delta + 2^23 (24-bit little endian each), stride.


int js_regexp_case_u24(char* data, int offset):
\treturn (data[offset] & 255) | ((data[offset + 1] & 255) << 8) | ((data[offset + 2] & 255) << 16)


# Mapped value of cp, or cp itself when the table has no entry.
int js_regexp_case_lookup(char* data, int count, int cp):
\tint lo = 0
\tint hi = count
\twhile (lo < hi):
\t\tint mid = lo + (hi - lo) / 2
\t\tint first = js_regexp_case_u24(data, mid * 10)
\t\tint last = js_regexp_case_u24(data, mid * 10 + 3)
\t\tif (cp < first): hi = mid
\t\telse if (cp > last): lo = mid + 1
\t\telse:
\t\t\tif ((cp - first) % (data[mid * 10 + 9] & 255) != 0): return cp
\t\t\treturn cp + js_regexp_case_u24(data, mid * 10 + 6) - 8388608
\treturn cp


# Appends every x != target that maps to target.
void js_regexp_case_preimages(char* data, int count, int target, list[int] out):
\tfor i in range(count):
\t\tint first = js_regexp_case_u24(data, i * 10)
\t\tint last = js_regexp_case_u24(data, i * 10 + 3)
\t\tint x = target - (js_regexp_case_u24(data, i * 10 + 6) - 8388608)
\t\tif (x != target && x >= first && x <= last && (x - first) % (data[i * 10 + 9] & 255) == 0): out.push(x)


char* js_regexp_fold_data():
\treturn c"{encode(fold)}"


int js_regexp_fold_count():
\treturn {len(fold)}


char* js_regexp_upper_data():
\treturn c"{encode(upper)}"


int js_regexp_upper_count():
\treturn {len(upper)}
'''


def main() -> int:
    text = render()
    if sys.argv[1:] == ["--check"]:
        if OUTPUT.read_text() != text:
            print(f"{OUTPUT} is stale; run tools/javascript_regexp_case.py", file=sys.stderr)
            return 1
        return 0
    if sys.argv[1:]:
        print(__doc__, file=sys.stderr)
        return 2
    OUTPUT.write_text(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
