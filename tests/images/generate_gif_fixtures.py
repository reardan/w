"""Regenerate original synthetic GIF fixtures and Pillow pixel oracles (Pillow 10+)."""
from io import BytesIO
from pathlib import Path
import random
import struct
from PIL import Image


def pack_codes(codes):
    bits = width = 3
    next_code, previous = 6, False
    value = used = 0
    data = bytearray()
    for code in codes:
        value |= code << used
        used += width
        while used >= 8:
            data.append(value & 255)
            value >>= 8
            used -= 8
        if code == 4:
            width, next_code, previous = bits, 6, False
        elif code != 5:
            if previous and next_code < 4096:
                next_code += 1
                if next_code == 1 << width and width < 12:
                    width += 1
            previous = True
    if used:
        data.append(value)
    return bytes(data)


def custom(width, height, codes, *, left=0, top=0, local=False, transparent=False, interlace=False, split=255):
    palette = bytes([255, 0, 0, 0, 255, 0, 0, 0, 255, 0, 0, 0])
    data = b'GIF89a' + struct.pack('<HHBBB', width + left, height + top, 0 if local else 129, 0, 0)
    if not local:
        data += palette
    data += b'!\xfe\x03abc\x00'  # Comment extension.
    if transparent:
        data += b'!\xf9\x04\x01\x00\x00\x03\x00'
    data += b',' + struct.pack('<HHHHB', left, top, width, height, (129 if local else 0) | (64 if interlace else 0))
    if local:
        data += palette
    compressed = pack_codes(codes)
    data += b'\x02'
    for start in range(0, len(compressed), split):
        block = compressed[start:start + split]
        data += bytes([len(block)]) + block
    return data + b'\x00;'


def cases():
    yield 'offset', custom(2, 2, [4, 0, 1, 2, 3, 5], left=1, top=1, local=True, transparent=True, split=1)
    yield 'background', custom(2, 1, [4, 1, 2, 5], left=1, top=1)
    yield 'kwkwk', custom(7, 1, [4, 0, 6, 7, 0, 5])
    yield 'deferred', custom(5000, 1, [4] + [i % 4 for i in range(5000)] + [5])
    rows = [0, 8, 4, 2, 6, 1, 3, 5, 7]
    yield 'interlace', custom(3, 9, [n for row in rows for i in range(3) for n in (4, (row + i) % 4)] + [5], interlace=True)
    rng = random.Random(710)
    im = Image.new('P', (80, 80))
    im.putpalette([n for i in range(256) for n in (i, (i * 3) % 256, 255 - i)])
    im.putdata([rng.randrange(256) for _ in range(6400)])
    out = BytesIO()
    im.save(out, format='GIF', interlace=True, optimize=False)
    yield 'pillow', out.getvalue()


def literal(data):
    return 'c"' + ''.join(f'\\x{n:02x}' for n in data) + '"'


def main():
    lines = ['# Original synthetic fixtures; generated by generate_gif_fixtures.py.\n']
    for name, data in cases():
        image = Image.open(BytesIO(data)).convert('RGBA')
        pixels = bytearray(image.tobytes())
        # RGB under zero alpha is not a visible color and need not be retained.
        for p in range(0, len(pixels), 4):
            if pixels[p + 3] == 0:
                pixels[p:p + 3] = b'\x00\x00\x00'
        lines += [f'const int gif_fixture_{name}_length = {len(data)}',
                  f'char* gif_fixture_{name}():\n\treturn {literal(data)}\n',
                  f'char* gif_golden_{name}():\n\treturn {literal(pixels)}\n']
    for name, codes in [('no_clear', [0, 5]), ('bad_code', [4, 7, 5]),
                        ('too_many', [4, 0, 1, 5]), ('too_few', [4, 5]),
                        ('no_eoi', [4, 0])]:
        data = custom(1, 1, codes)
        lines += [f'const int gif_bad_{name}_length = {len(data)}',
                  f'char* gif_bad_{name}():\n\treturn {literal(data)}\n']
    Path(__file__).with_name('gif_fixtures.w').write_text('\n'.join(lines))


if __name__ == '__main__':
    main()
